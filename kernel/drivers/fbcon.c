/**
 * TocinOS framebuffer splash console (fbcon)
 *
 * Renders the M1 boot splash to the TocinBoot GOP framebuffer and mirrors
 * kernel boot-log lines beneath it (docs/ROADMAP.md M1: "Graphical splash;
 * kernel renders to GOP framebuffer").
 *
 * Efficiency notes (roadmap §2.7): everything is rendered write-once with
 * plain 32-bit stores through per-row pointers — no per-pixel function
 * calls, no dynamic allocation. The only allocation in this file happens
 * inside vmm_map_page() when it creates the page table(s) covering the
 * framebuffer range.
 *
 * v1 limitations (documented, deliberate): 32bpp formats only; no
 * scrollback — when the log region below the splash fills up it is cleared
 * and the cursor restarts at the top of the region (the splash itself is
 * never disturbed). A real framebuffer console is an M3 item.
 */

