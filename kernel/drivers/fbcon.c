int fbcon_active(void) {
    return fbcon.active;
}

int fbcon_init(void) {
    const bootinfo_fb_t *fb = bootinfo_framebuffer();

    if (!fb || fb->bpp != 32 || fb->pitch < fb->width * 4) {
        return -1; /* legacy boot path or unusable mode: stay inactive */
    }

    /* Resolve the 8-bit channel shifts for this pixel format. */
    switch (fb->format) {
    case TOCINBOOT_FB_XRGB32:
        fbcon_rs = 16; fbcon_gs = 8; fbcon_bs = 0;
        break;
    case TOCINBOOT_FB_XBGR32:
        fbcon_rs = 0;  fbcon_gs = 8; fbcon_bs = 16;
        break;
    case TOCINBOOT_FB_BITMASK:
        if (fb->red_size != 8 || fb->green_size != 8 || fb->blue_size != 8) {
            serial_printf("[FBCON] unsupported bitmask format, skipping\n");
            return -1;
        }
        fbcon_rs = fb->red_shift;
        fbcon_gs = fb->green_shift;
        fbcon_bs = fb->blue_shift;
        break;
    default:
        serial_printf("[FBCON] unsupported fb format %u, skipping\n",
                      fb->format);
        return -1;
    }

    /* The framebuffer is MMIO above the identity-mapped low 4MB
     * (0x80000000 on OVMF), so identity-map its page-aligned range
     * before the first store. PAGE_PCD|PAGE_PWT: uncached device
     * memory. vmm_map_page() ORs in PAGE_PRESENT itself. This 32-bit
     * kernel cannot reach a framebuffer at or above 4GB. */
    uint64_t map_len = (uint64_t)fb->pitch * (uint64_t)fb->height;
    if (fb->base >= 0xFFFFFFFFull || fb->base + map_len > 0xFFFFFFFFull) {
        serial_printf("[FBCON] fb above 4GB, skipping\n");
        return -1;
    }
    uint32_t map_start = (uint32_t)fb->base & ~0xFFFu;
    uint32_t map_end = ((uint32_t)(fb->base + map_len) + 0xFFFu) & ~0xFFFu;
    for (uint32_t addr = map_start; addr < map_end; addr += PAGE_SIZE) {
        vmm_map_page(addr, addr, PAGE_WRITE | PAGE_PCD | PAGE_PWT);
    }

    fbcon.fb = (volatile uint32_t *)(uint32_t)fb->base;
    fbcon.width = fb->width;
    fbcon.height = fb->height;
    fbcon.pitch32 = fb->pitch / 4;
    fbcon.px_bg = fbcon_pack(FBCON_RGB_BG);
    fbcon.px_log = fbcon_pack(FBCON_RGB_LOG);

    uint32_t px_title = fbcon_pack(FBCON_RGB_TITLE);
    uint32_t px_accent = fbcon_pack(FBCON_RGB_ACCENT);
    uint32_t px_dim = fbcon_pack(FBCON_RGB_DIM);

    /* ---- splash: clear, centered wordmark, accent rule, version, ---- */
    /* ---- status line. Everything is drawn exactly once.          ---- */
    static const char wordmark[] = "TocinOS";
    static const char version[] = "v2.0";
    static const char status[] = "booting...";

    uint32_t scale = (fbcon.width >= 640 && fbcon.height >= 400) ? 4 : 2;
    uint32_t wm_w = fbcon_strlen(wordmark) * FBCON_GLYPH_W * scale;
    uint32_t wm_h = FBCON_GLYPH_H * scale;
    uint32_t wm_x = (fbcon.width - wm_w) / 2;
    uint32_t wm_y = fbcon.height / 4;
    uint32_t rule_y = wm_y + wm_h + 14;
    uint32_t ver_y = rule_y + 2 + 12;
    uint32_t status_y = ver_y + FBCON_GLYPH_H + 8;

    fbcon_fill(0, 0, fbcon.width, fbcon.height, fbcon.px_bg);
    fbcon_text(wm_x, wm_y, wordmark, scale, px_title, fbcon.px_bg);
    fbcon_fill(wm_x, rule_y, wm_w, 2, px_accent);
    fbcon_text((fbcon.width - fbcon_strlen(version) * FBCON_GLYPH_W) / 2,
               ver_y, version, 1, px_dim, fbcon.px_bg);
    fbcon_text((fbcon.width - fbcon_strlen(status) * FBCON_GLYPH_W) / 2,
               status_y, status, 1, px_dim, fbcon.px_bg);

    fbcon.log_top = status_y + FBCON_GLYPH_H + 24;
    fbcon.cur_x = FBCON_MARGIN_X;
    fbcon.cur_y = fbcon.log_top;
    fbcon.active = 1;

    /* CI-greppable proof that the splash hit the framebuffer. */
    serial_printf("[FBCON] splash rendered %ux%ux%u @ 0x%x\n",
                  fb->width, fb->height, fb->bpp, (uint32_t)fb->base);
    return 0;
}

void fbcon_puts(const char *str) {
    if (!fbcon.active || !str) {
        return;
    }
    while (*str) {
        char c = *str++;
        if (c == '\n') {
            fbcon.cur_x = FBCON_MARGIN_X;
            fbcon.cur_y += FBCON_GLYPH_H;
        } else if (c == '\r') {
            fbcon.cur_x = FBCON_MARGIN_X;
        } else if (c == '\b') {
            if (fbcon.cur_x > FBCON_MARGIN_X) {
                fbcon.cur_x -= FBCON_GLYPH_W;
                fbcon_glyph(fbcon.cur_x, fbcon.cur_y, ' ', 1,
                            fbcon.px_log, fbcon.px_bg);
            }
        } else {
            if (c == '\t') {
                c = ' ';
            }
            if (fbcon.cur_x + FBCON_GLYPH_W > fbcon.width) { /* wrap */
                fbcon.cur_x = FBCON_MARGIN_X;
                fbcon.cur_y += FBCON_GLYPH_H;
            }
            if (fbcon.cur_y + FBCON_GLYPH_H > fbcon.height) {
                /* Crude v1 "scroll": wipe the log region (splash stays)
                 * and restart at its top. Real scrolling is M3. */
                fbcon_fill(0, fbcon.log_top, fbcon.width,
                           fbcon.height - fbcon.log_top, fbcon.px_bg);
                fbcon.cur_x = FBCON_MARGIN_X;
                fbcon.cur_y = fbcon.log_top;
            }
            fbcon_glyph(fbcon.cur_x, fbcon.cur_y, c, 1,
                        fbcon.px_log, fbcon.px_bg);
            fbcon.cur_x += FBCON_GLYPH_W;
        }
        /* Newlines can also push the cursor past the bottom: handled on
         * the next printable character above. */
    }
}
