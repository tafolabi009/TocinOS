#define FBCON_GLYPH_W   8
#define FBCON_GLYPH_H   16
#define FBCON_MARGIN_X  16      /* left margin of the log region (px)  */

/* Splash palette (r,g,b) — packed into pixels once in fbcon_init().   */
#define FBCON_RGB_BG      0x10, 0x14, 0x1A  /* near-black slate        */
#define FBCON_RGB_TITLE   0xE8, 0xEC, 0xF2  /* near-white wordmark     */
#define FBCON_RGB_ACCENT  0xE8, 0x94, 0x3A  /* warm amber rule         */
#define FBCON_RGB_DIM     0x9A, 0xA4, 0xB0  /* version / status text   */
#define FBCON_RGB_LOG     0xC2, 0xCA, 0xD4  /* boot log text           */

static struct {
    volatile uint32_t *fb;   /* mapped framebuffer base                */
    uint32_t width;          /* visible pixels per row                 */
    uint32_t height;         /* visible rows                           */
    uint32_t pitch32;        /* 32-bit words per row (pitch / 4)       */
    uint32_t px_bg;          /* packed background pixel                */
    uint32_t px_log;         /* packed log-text pixel                  */
    uint32_t cur_x, cur_y;   /* log cursor (pixels)                    */
    uint32_t log_top;        /* first pixel row of the log region      */
    int active;
} fbcon;

/* Pack an (r,g,b) triple using the channel layout handed off by the
 * bootloader. Called a handful of times at init only — pixels are
 * cached, never re-packed per store. */
static uint8_t fbcon_rs, fbcon_gs, fbcon_bs; /* channel shifts */

static uint32_t fbcon_pack(uint8_t r, uint8_t g, uint8_t b) {
    return ((uint32_t)r << fbcon_rs) |
           ((uint32_t)g << fbcon_gs) |
           ((uint32_t)b << fbcon_bs);
}

/* Solid rectangle, clipped, row pointer + 32-bit stores. */
static void fbcon_fill(uint32_t x, uint32_t y, uint32_t w, uint32_t h,
                       uint32_t px) {
    if (x >= fbcon.width || y >= fbcon.height) {
        return;
    }
    if (x + w > fbcon.width)  { w = fbcon.width - x; }
    if (y + h > fbcon.height) { h = fbcon.height - y; }
    for (uint32_t row = 0; row < h; row++) {
        volatile uint32_t *p = fbcon.fb + (y + row) * fbcon.pitch32 + x;
        for (uint32_t col = 0; col < w; col++) {
            p[col] = px;
        }
    }
}

/* One glyph at integer scale (scale=1 → 8x16). Opaque: background is
 * painted too, so overwriting a cell fully erases what was there. */
static void fbcon_glyph(uint32_t x, uint32_t y, char c, uint32_t scale,
                        uint32_t fg, uint32_t bg) {
    if (c < 32 || c > 126) {
        c = '?';
    }
    const unsigned char *g = fbcon_font8x16[c - 32];
    if (x + FBCON_GLYPH_W * scale > fbcon.width ||
        y + FBCON_GLYPH_H * scale > fbcon.height) {
        return;
    }
    for (uint32_t row = 0; row < FBCON_GLYPH_H; row++) {
        unsigned char bits = g[row];
        for (uint32_t sy = 0; sy < scale; sy++) {
            volatile uint32_t *p =
                fbcon.fb + (y + row * scale + sy) * fbcon.pitch32 + x;
            for (uint32_t col = 0; col < FBCON_GLYPH_W; col++) {
                uint32_t px = (bits & (0x80u >> col)) ? fg : bg;
                for (uint32_t sx = 0; sx < scale; sx++) {
                    *p++ = px;
                }
            }
        }
    }
}

static void fbcon_text(uint32_t x, uint32_t y, const char *s, uint32_t scale,
                       uint32_t fg, uint32_t bg) {
    while (*s) {
        fbcon_glyph(x, y, *s++, scale, fg, bg);
        x += FBCON_GLYPH_W * scale;
    }
}

static uint32_t fbcon_strlen(const char *s) {
    uint32_t n = 0;
    while (s[n]) {
        n++;
    }
    return n;
}

